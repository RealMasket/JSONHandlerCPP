"""Regenerate exact comparison fixtures using Python's rational arithmetic.

No Python dependency is needed to build or run the C++ tests. Fractions capture
the exact binary64 value of each floating literal, not its rounded decimal text.
"""
from fractions import Fraction
import json
import math
from pathlib import Path
import random

MIN_SIGNED = -(1 << 63)
MAX_UNSIGNED = (1 << 64) - 1
cases = {}


def exact(text):
    return Fraction(float(text)) if any(c in text for c in ".eE") else Fraction(int(text))


def add(left, right):
    a, b = exact(left), exact(right)
    cases[left, right] = (a > b) - (a < b)


boundaries = [
    MIN_SIGNED, MIN_SIGNED + 1, -(1 << 53) - 1, -1, 0, 1,
    (1 << 53) - 1, 1 << 53, (1 << 53) + 1,
    (1 << 63) - 2, (1 << 63) - 1, 1 << 63,
    MAX_UNSIGNED - 1, MAX_UNSIGNED,
]
for number in boundaries:
    floating = float(number)
    for neighbor in (floating, math.nextafter(floating, -math.inf),
                     math.nextafter(floating, math.inf)):
        add(str(number), repr(neighbor))
    if number < MAX_UNSIGNED:
        add(str(number), str(number + 1))

for integer in (-2, -1, 0, 1, 2):
    for floating in (-1.5, -0.5, -0.0, 0.0, 0.5, 1.5,
                     math.ulp(0.0), -math.ulp(0.0)):
        add(str(integer), repr(floating))

rng = random.Random(20261105)
for _ in range(96):
    # Integers close to representable doubles exercise rounded-neighbor ties.
    integer = rng.randint(MIN_SIGNED, MAX_UNSIGNED)
    floating = float(integer)
    floating = math.nextafter(floating, rng.choice([-math.inf, math.inf]))
    add(str(integer), repr(floating))

for left, right in [
    ("-0.0", "0.0"), ("1.5", "1.5000000000000002"),
    ("1e308", "1.7976931348623157e308"),
    ("-1e308", "1e308"), ("5e-324", "0.0"),
]:
    add(left, right)

lines = [
    "// Generated by tests/generate_number_comparisons.py; do not edit by hand.",
    "// Expected ordering uses independent exact Fraction arithmetic.",
    "#pragma once",
    "struct NumberComparisonCase { const char* left; const char* right; int order; };",
    "inline constexpr NumberComparisonCase numberComparisonCases[] = {",
]
for (left, right), order in cases.items():
    lines.append(f"    {{{json.dumps(left)}, {json.dumps(right)}, {order}}},")
lines += ["};", ""]
output = Path(__file__).resolve().parent / "data" / "NumberComparisonCases.hpp"
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {len(cases)} exact number comparison cases")
